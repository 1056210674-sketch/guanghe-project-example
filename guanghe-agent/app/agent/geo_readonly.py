def _plain(value: str) -> str:
    """Render authorized names/quotes as literal text, not executable Markdown/HTML."""
    escaped = html.escape(" ".join(value.split()), quote=False)
    for char in ("\\", "`", "*", "_", "[", "]", "(", ")", "#", "!", "|"):
        escaped = escaped.replace(char, "\\" + char)
    return escaped


def _rate(value: float | None) -> str:
    return "尚不能评估" if value is None else f"{value:g}%"


def _trend_fact(platform: GeoInsightTrendPlatform) -> str:
    label = _PLATFORMS[platform.platform_code]
    when = platform.current_observed_at.astimezone(timezone(timedelta(hours=8))).strftime(
        "%Y/%m/%d %H:%M"
    )
    current = f"本期可见度 {_rate(platform.current_mention_rate)}"
    if platform.comparison_status == "COMPARABLE" and (
        platform.delta_percentage_points is not None
        and platform.previous_mention_rate is not None
        and platform.current_mention_rate is not None
        and platform.common_samples is not None
        and platform.common_samples > 0
    ):
        delta = platform.delta_percentage_points
        direction = "上升" if delta > 0 else "下降" if delta < 0 else "持平"
        change = "持平" if delta == 0 else f"{direction} {abs(delta):g} 个百分点"
        reason = (
            f"共同有效样本 {platform.common_samples} 条；"
            f"上期 {_rate(platform.previous_mention_rate)}，{current}，{change}。"
        )
    elif platform.comparison_status == "FIRST_OBSERVATION":
        reason = f"{current}；这是所选时间窗口中的首次观测，暂没有上期比较。"
    elif platform.comparison_reason == "PLATFORM_NOT_SAMPLED":
        missing = {
            "PREVIOUS": "上期没有采样该平台",
            "CURRENT": "本期没有采样该平台",
            "BOTH": "两期都没有采样该平台",
        }.get(
            platform.missing_period or "",
            "两期中至少有一期没有采样该平台，现有信息不足以确定是哪一期",
        )
        reason = f"{current}；{missing}，不能判断变化。"
    else:
        reason = f"{current}；" + _TREND_REASONS.get(
            platform.comparison_reason or "", "本次尚未形成有效的比较结果，不能判断变化。"
        )
    if platform.current_report_id is None:
        reason += "这次观测尚无可查看的报告。"
    return f"{label} ({when}，北京时间): {reason}"


def build_geo_fact_catalog(context: AuthorizedRunContext) -> GeoFactCatalog:
    """Build exclusively from this Run's scope; no history prose, writes or extra queries."""
    snapshot = context.geo_insight_context
    serialized = "null" if snapshot is None else snapshot.model_dump_json(by_alias=True)
    # Scope nonce includes the opaque per-Run authorization handle but never exposes it.
    scope_ref = hashlib.sha256(f"{context.user_context_ref}\n{serialized}".encode()).hexdigest()[
        :24
    ]
    facts: dict[str, str] = {}
    quotes: dict[str, str] = {}
    links: dict[str, str] = {}
    if snapshot is None:
        return GeoFactCatalog(
            scope_ref,
            "",
            "本轮没有可核实的监测报告，请先选择要查看的商品或报告。",
            facts,
            quotes,
            links,
        )
    links["overview"] = f"[查看监测趋势]({snapshot.links.overview_path})"
    if snapshot.status != "READY":
        messages = {
            "NEEDS_SCOPE": "请先选择要查看的经营空间或商品，再查看它的监测结果。",
            "NEEDS_TOPIC": "当前范围有多个监测专题，请先选择其中一个，避免混合不同范围的结论。",
            "NO_REPORT": "当前选择范围内尚未找到监测报告。这不代表商品可见度为零。",
            "UNAVAILABLE": "监测结果暂时无法读取，请稍后重试。这不代表商品没有被提到。",
        }
        for index, topic in enumerate(snapshot.topic_choices):
            links[f"topic-{index}"] = f"[{_plain(topic.name)}]({topic.href})"
        if snapshot.status == "NO_REPORT" and snapshot.topic_choices:
            messages["NO_REPORT"] += (
                " 已有监测专题，请打开下方专题继续配置问题和平台，并核对报价后确认。"
                "本轮没有新建专题或开始监测。"
            )
        elif snapshot.status == "NO_REPORT":
            scope = general_response_platform_scope(context)
            if scope["geoMonitorPreparationAvailable"]:
                links["overview"] = f"[监测入口]({snapshot.links.overview_path})"
                messages["NO_REPORT"] += (
                    " 可以从下方监测入口准备本次对象和顾客问题，选择可用平台，"
                    "查看系统给出的真实报价；有有效授权后才会运行。"
                    "当前没有开始监测、扣积分或发布，不需要你先去各个平台逐个截图。"
                )
            elif scope["geoMonitorSupported"]:
                messages["NO_REPORT"] += (
                    " GEO 智能体支持监测，但当前选择暂不能准备；先核对项目和监测配置，"
                    "再核对问题、平台、报价及执行授权。当前没有开始监测或扣积分。"
                )
            else:
                messages["NO_REPORT"] += (
                    " 要实际监测，请先选择已启用的 GEO 智能体，再准备对象、问题并核对报价。"
                    "当前没有开始监测或扣积分。"
                )
        return GeoFactCatalog(scope_ref, "", messages[snapshot.status], facts, quotes, links)
    report = snapshot.report
    assert report is not None
    when = report.generated_at.astimezone(timezone(timedelta(hours=8))).strftime("%Y/%m/%d %H:%M")
    target = _plain(report.target.name) if report.target is not None else "本专题监测对象"
    header = f"{target} · {_plain(report.title)}\n\n报告时间: {when} (北京时间)"
    for item in report.platforms:
        code = item.platform_code.lower()
        mentions = (
            "暂不能判定提及情况"
            if item.mentioned_samples is None
            else (f"{item.mentioned_samples} 条明确提及")
        )
        facts[f"report.{code}"] = (
            f"{_PLATFORMS[item.platform_code]}: 可见度 {_rate(item.mention_rate)}；"
            f"{item.valid_samples} 条有效回答中，{mentions}。"
            f"计划 {item.expected_samples} 条，失败 {item.failed_samples} 条，"
            f"缺失 {item.missing_samples} 条。"
        )
    if not report.platforms:
        facts["report.unavailable"] = "当前报告没有可评估的自然发现样本，不能将可见度记作零。"
    known_mentions = [item for item in report.platforms if item.mentioned_samples is not None]
    valid = sum(item.valid_samples for item in known_mentions)
    mentions = sum(item.mentioned_samples or 0 for item in known_mentions)
    if report.target is None:
        baseline = (
            "这份报告尚未明确公开的监测对象，不能据此评判品牌可见度。"
            "先确认对外使用的店名或品牌名称及别名，不把项目名称自动当成品牌。"
        )
    elif valid > 0 and mentions == 0:
        baseline = (
            "本报告可判定的有效回答暂未明确提及监测对象；"
            "可先把对外介绍和顾客会问的问题写清楚，但不能据此断言未提及的原因。"
        )
    elif valid > 0:
        baseline = (
            "本报告已有有效回答提及监测对象；先核对已有回答的语境，"
            "再补充尚未讲清楚的信息，不把提及当成推荐或排名。"
        )
    else:
        baseline = "本报告尚无可判定提及的有效样本；可以先准备资料，不把未知写成零可见度。"
    knowledge = context.knowledge_context
    material = (
        "沿用本轮项目知识库中已经提供的原始资料，不要求重新填写；"
        if knowledge is not None and any(doc.paragraphs for doc in knowledge.documents)
        else "先整理已经确认的介绍；缺少必要经营资料时再补一个关键事实；"
    )
    facts["content.baseline"] = baseline
    facts["content.step-one"] = (
        "1. 先整理一份准确的对外介绍。"
        + material
        + "写清名称、主营内容和适用需求。地址、营业时间、价格、参数等没有确认的先不写。"
    )
    facts["content.step-two"] = (
        "2. 再准备一篇问题解答或选购介绍。围绕这份报告的问题范围选择一个顾客需求，"
        "说明如何判断是否适合自己；只使用已确认的特点，不照抄竞品卖点，"
        "不把报告中的未提及或引用线索写成经营事实。"
    )
    gaps = sum(item.failed_samples + item.missing_samples for item in report.platforms)
    facts["content.step-three"] = (
        "3. 最后列出待核对项，先给你看内容方向。"
        + (
            "这份报告还有失败或缺失的回答，相关平台先保持未评估，不按未提及作改进判断。"
            if gaps
            else "之后若复测，保持问题范围和平台口径一致，再比较有效回答。"
        )
        + "真正生成文章或重新监测前仍须核对相应报价和授权，发布仍需你确认。"
    )
    trend = snapshot.trend
    if trend is None or trend.status != "READY" or not trend.platforms:
        facts["trend.unavailable"] = "本轮暂未取得可比较的趋势数据，不能判断进步或退步。"
    else:
        for item in trend.platforms:
            facts[f"trend.{item.platform_code.lower()}"] = _trend_fact(item)
        if trend.history_truncated:
            facts["trend.partial"] = "当前只读取了部分历史范围，不能据此概括全部历史。"
    competitors = snapshot.competitors
    if competitors is None or competitors.status != "SUCCEEDED":
        facts["competitor.unavailable"] = "本轮没有可用的已保存竞品解读，不能据此断定没有竞品。"
        facts["registration.unavailable"] = "本轮无法核实竞品目录登记状态，请在竞品工作台查看。"
    else:
        for pi, platform in enumerate(competitors.platforms):
            for ei, entity in enumerate(platform.entities):
                if entity.role == "OWN" or entity.recognition_status == "IGNORED":
                    continue
                mentions = (
                    "提及情况暂未判定"
                    if entity.mentioned_units is None
                    else (f"{platform.valid_units} 条有效回答中提及 {entity.mentioned_units} 条")
                )
                facts[f"competitor.p{pi}.e{ei}"] = (
                    f"{_plain(entity.name)} · {_PLATFORMS[platform.platform_code]}: "
                    f"{mentions}，提及比例 {_rate(entity.mention_rate)}。"
                )
        for ci, candidate in enumerate(competitors.candidates):
            name = _plain(candidate.name)
            status = {
                "CONFIRMED": "此前已登记或关联正式竞品目录；不代表已加入当前专题或自动监测计划。",
                "PENDING": "待确认候选，尚未通过此候选记录登记为正式竞品。",
                "IGNORED": "此前已忽略，本轮不会将其重新推荐为待加入竞品。",
            }.get(candidate.status, "目前的登记状态需要在竞品工作台核实。")
            facts[f"registration.c{ci}"] = f"{name}: {status}"
            if candidate.status == "IGNORED":
                continue
            for qi, evidence in enumerate(candidate.evidence):
                # Evidence from a different report cannot leak into the selected report's reply.
                if evidence.report_id != report.report_id or not evidence.quote.strip():
                    continue
                quotes[f"quote.c{ci}.q{qi}"] = (
                    f"关于{name}，该次 AI 回答原文写道: “{_plain(evidence.quote)}”。"
                )
        if not any(key.startswith("competitor.") for key in facts):
            facts["competitor.none"] = (
                "这份已保存解读中没有可展示的竞品提及统计；不等于全网没有竞品。"
            )
        if not any(key.startswith("registration.") for key in facts):
            facts["registration.none"] = "这份解读没有候选登记记录，请在竞品工作台查看完整目录。"
        if competitors.evidence_truncated:
            facts["competitor.partial"] = "当前竞品证据为部分摘录，不是完整竞品清单。"
    if snapshot.links.report_path is not None:
        links["report"] = f"[查看本次报告]({snapshot.links.report_path})"
    if snapshot.links.competitive_path is not None:
        links["competitors"] = f"[打开竞品工作台]({snapshot.links.competitive_path})"
    return GeoFactCatalog(scope_ref, header, None, facts, quotes, links)


def _default_selection(
    catalog: GeoFactCatalog, focus: GeoReadFocus = "OVERVIEW"
) -> GeoReadSelection:
    return GeoReadSelection(
        scopeRef=catalog.scope_ref,
        focus=focus,
        factRefs=tuple(key for key in catalog.facts if key.startswith(_FOCUS_PREFIXES[focus]))[:16],
        quoteRefs=(),
        linkRefs=tuple(key for key in ("report", "overview") if key in catalog.links),
    )


def render_geo_selection(catalog: GeoFactCatalog, selection: GeoReadSelection) -> str:
    """Fail closed on invented, duplicated or cross-scope references before producing any text."""
    if selection.scope_ref != catalog.scope_ref:
        raise ValueError("GEO_SELECTION_SCOPE_MISMATCH")
    for refs, available in (
        (selection.fact_refs, catalog.facts),
        (selection.quote_refs, catalog.quotes),
        (selection.link_refs, catalog.links),
    ):
        if len(refs) != len(set(refs)) or any(ref not in available for ref in refs):
            raise ValueError("GEO_SELECTION_REFERENCE_INVALID")
    if catalog.status_message is not None:
        return catalog.status_message + "\n\n" + " · ".join(catalog.links.values())
    focus = selection.focus
    allowed = _FOCUS_PREFIXES[focus]
    if any(not ref.startswith(allowed) for ref in selection.fact_refs):
        raise ValueError("GEO_SELECTION_FOCUS_MISMATCH")
    if focus != "COMPETITORS" and selection.quote_refs:
        raise ValueError("GEO_SELECTION_FOCUS_MISMATCH")
    refs = selection.fact_refs or _default_selection(catalog, focus).fact_refs
    if focus == "CONTENT_PLAN":
        # The selector cannot hide ordered actions or their evidence limitations.
        refs = tuple(ref for ref in catalog.facts if ref.startswith(("report.", "content.")))
    # Scope limitations are compulsory; the selector cannot hide truncation.
    partial_ref = "trend.partial" if focus == "TREND" else "competitor.partial"
    if (
        focus in {"TREND", "COMPETITORS"}
        and partial_ref in catalog.facts
        and partial_ref not in refs
    ):
        refs = (*refs, partial_ref)
    parts = [f"### {_FOCUS_TITLE[focus]}", catalog.header]
    if focus == "SAMPLE_QUALITY":
        parts.append("失败或缺失表示没有取得可评估的回答，既不能算作未提及，也不能证明被提及。")
    parts.append("\n".join(f"- {catalog.facts[ref]}" for ref in refs))
    if focus == "CONTENT_PLAN":
        parts.append(
            "以上是根据这份历史报告提出的内容准备建议，不是遗漏原因或效果结论。"
            "本轮没有生成文章、创建付费任务、扣积分或发布，也不承诺发文后可见度提升。"
        )
    elif focus == "TREND":
        parts.append(
            "以上仅比较近 30 天内的共同样本；平台未采样或采样信息不足不代表没有历史记录。"
            "趋势与本次报告的题目筛选口径不同，不能将两处比例直接相减；变化不代表优化的因果效果。"
        )
    elif focus == "REGISTRATION":
        parts.append(
            "本轮只查看已有记录，没有新增、确认或忽略竞品，也没有修改专题或监测计划。需要变更时请在工作台核对确认。"
        )
    elif focus == "COMPETITORS":
        parts.append(
            "提及比例仅反映这份报告的有效回答样本，不是排名、推荐或市场份额；现有证据不能解释竞品为何被提到。"
        )
        if selection.quote_refs:
            parts.append(
                "#### 回答中的原文线索\n\n"
                + "\n\n".join(catalog.quotes[ref] for ref in selection.quote_refs)
            )
            parts.append("以上是 AI 回答的说法，未经独立核实，不能直接当作自家商品事实。")
        parts.append(
            "目前聊天只展示已有提及证据；具体问题、原始回答和来源可在竞品工作台核对，不在这里推导竞品胜因或自动制定改进计划。"
        )
    else:
        parts.append(
            "可见度按有效回答中的明确名称提及统计；失败、缺失另列，不作未提及。仅代表本次范围，不等于全网表现。"
        )
    if selection.link_refs:
        parts.append(" · ".join(catalog.links[ref] for ref in selection.link_refs))
    return "\n\n".join(part for part in parts if part)


def _selection_fallback(catalog: GeoFactCatalog) -> str:
    links = " · ".join(
        catalog.links[key] for key in ("report", "overview", "competitors") if key in catalog.links
    )
    message = (
        "本次未能准确对应你要查看的信息。当前聊天只读取已有结果；"
        "竞品登记、问题或计划调整请到工作台核对确认，本轮未执行变更。"
    )
    return message + (f"\n\n{links}" if links else "")


def _safe_competitor_fallback(catalog: GeoFactCatalog, question: str) -> str | None:
    """Use saved evidence for an unmistakable read-only competitor question only."""
    if catalog.status_message is not None:
        return None
    compact = "".join(question.split())
    if not re.search(r"(?:竞品|竞争品牌|其他品牌|别人的牌子)", compact):
        return None
    if not re.search(r"(?:哪里|哪些|有什么|表现|提到|提及|强|优势|情况|对比)", compact):
        return None
    if re.search(
        r"(?:加进|加入|录入|入库|登记|删除|修改|改掉|创建|保存|确认|"
        r"开始监测|自动监测|发布|投稿|编造|伪造|假装|https?://)",
        compact,
        re.IGNORECASE,
    ):
        return None
    selection = _default_selection(catalog, "COMPETITORS").model_copy(
        update={
            "link_refs": tuple(key for key in ("report", "competitors") if key in catalog.links)
        }
    )
    return render_geo_selection(catalog, selection)


class GeoReadOnlyRuntime:
    def __init__(
        self, *, gateway: ModelGateway, harness: RuntimeHarness, selector_prompt: str
    ) -> None:
        self._gateway = gateway
        self._harness = harness
        self._selector_prompt = selector_prompt

    async def execute(
        self,
        *,
        request: ChatRunRequest,
        context: AuthorizedRunContext,
        counters: RuntimeUsageCounters,
        on_delta: DeltaHandler | None,
    ) -> GeoReadResult:
        catalog = build_geo_fact_catalog(context)
        selection = _default_selection(catalog)
        usage = GatewayUsage()
        estimated = 0
        fallback: str | None = None
        selection_error_code: str | None = None
        failure_stage: str | None = None
        if catalog.status_message is None and isinstance(
            self._gateway, StructuredCompletionGateway
        ):
            history = (
                () if context.conversation_memory is None else context.conversation_memory.messages
            )
            recent_questions = [
                content[:400]
                for item in history
                if item.role == "USER"
                and isinstance(content := item.content.get("text"), str)
                and item.message_id != request.message.message_id
            ][-3:]
            data = json.dumps({"recentUserQuestions": recent_questions}, ensure_ascii=False)
            messages: ModelMessages = (
                ModelMessage(
                    role="system",
                    content=self._selector_prompt
                    + "\n\n"
                    + "<geo-fact-catalog>"
                    + catalog.model_json()
                    + "</geo-fact-catalog>",
                ),
                ModelMessage(role="user", content=data + "\n本轮问题: " + request.message.content),
            )
            fitted, estimated = self._harness.fit_model_messages(
                request,
                messages,
                target_input_tokens=request.budget.max_input_tokens,
                available_history_tokens=1,
            )
            counters.observe_estimated_input_tokens(estimated)
            with start_span(
                "agent.geo.readonly.select", attributes={"agent.geo.scopeStatus": "READY"}
            ) as span:
                try:
                    parsed, usage = await self._gateway.complete_structured(
                        fitted,
                        GeoReadSelection,
                        operation="readonly_geo_selection",
                        max_tokens=700,
                        error_code="DEEPSEEK_GEO_SELECTION_INVALID",
                        repair_instruction="Select existing references from the current catalog.",
                        repair_attempts=0,
                    )
                    selection = GeoReadSelection.model_validate(parsed)
                    text = render_geo_selection(catalog, selection)
                except ModelGatewayError as exc:
                    usage = exc.usage
                    fallback = "GEO_READONLY_SELECTION_UNAVAILABLE"
                    selection_error_code = exc.code
                    failure_stage = exc.failure_stage or "model_gateway"
                    span.fail(fallback)
                    text = _selection_fallback(catalog)
                except ValidationError:
                    fallback = "GEO_READONLY_SELECTION_INVALID"
                    selection_error_code = "GEO_SELECTION_SCHEMA_INVALID"
                    failure_stage = "selection_validation"
                    span.fail(fallback)
                    text = _selection_fallback(catalog)
                except ValueError as exc:
                    fallback = "GEO_READONLY_SELECTION_INVALID"
                    known_issues = {
                        "GEO_SELECTION_SCOPE_MISMATCH",
                        "GEO_SELECTION_REFERENCE_INVALID",
                        "GEO_SELECTION_FOCUS_MISMATCH",
                    }
                    selection_error_code = (
                        str(exc) if str(exc) in known_issues else "GEO_SELECTION_SCHEMA_INVALID"
                    )
                    failure_stage = "selection_validation"
                    span.fail(fallback)
                    text = _selection_fallback(catalog)
                counters.record_gateway_usage(usage)
        else:
            text = render_geo_selection(catalog, selection)
        if fallback is not None:
            safe_competitor_reply = (
                None
                if selection_error_code == "GEO_SELECTION_SCOPE_MISMATCH"
                else _safe_competitor_fallback(catalog, request.message.content)
            )
            if safe_competitor_reply is not None:
                text = safe_competitor_reply
            logger.warning(
                "geo_readonly_selection_fallback",
                extra={
                    "agentRunId": str(request.run_id),
                    "traceId": current_trace_id(),
                    "stableErrorCode": selection_error_code or fallback,
                    "failureStage": failure_stage,
                    "fallbackType": (
                        "SAVED_COMPETITOR_EVIDENCE"
                        if safe_competitor_reply is not None
                        else "CAPABILITY_BOUNDARY"
                    ),
                    "operation": "readonly_geo_selection",
                },
            )
        # Never pass on_delta to the model: only validated, deterministic text reaches SSE.
        if on_delta is not None:
            await on_delta(text)
        return GeoReadResult(text, usage, estimated, fallback, selection.focus)
