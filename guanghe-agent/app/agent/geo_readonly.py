GeoReadFocus = Literal[
    "OVERVIEW", "TREND", "COMPETITORS", "REGISTRATION", "SAMPLE_QUALITY", "CONTENT_PLAN"
]
EvidenceRef = Annotated[str, Field(min_length=1, max_length=64, pattern=r"^[a-z][a-z0-9.-]*$")]
logger = logging.getLogger(__name__)


class GeoReadSelection(BaseModel):
    """No prose, numbers, URLs or business actions can be generated by this selector."""

    model_config = ConfigDict(extra="forbid", frozen=True, populate_by_name=True)
    scope_ref: str = Field(alias="scopeRef", pattern=r"^[a-f0-9]{24}$")
    focus: GeoReadFocus
    fact_refs: tuple[EvidenceRef, ...] = Field(alias="factRefs", max_length=16)
    quote_refs: tuple[EvidenceRef, ...] = Field(alias="quoteRefs", max_length=4)
    link_refs: tuple[EvidenceRef, ...] = Field(alias="linkRefs", max_length=3)


@dataclass(frozen=True, slots=True)
class GeoFactCatalog:
    scope_ref: str
    header: str
    status_message: str | None
    facts: dict[str, str]
    quotes: dict[str, str]
    links: dict[str, str]

    def model_json(self) -> str:
        # Text is already a bounded, attributed data projection, never instructions.
        payload = {
            "scopeRef": self.scope_ref,
            "scope": self.header,
            "facts": self.facts,
            "quotes": self.quotes,
            "links": self.links,
        }
        return (
            json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
            .replace("<", "\\u003c")
            .replace(">", "\\u003e")
            .replace("&", "\\u0026")
        )


@dataclass(frozen=True, slots=True)
class GeoReadResult:
    text: str
    usage: GatewayUsage = field(default_factory=GatewayUsage)
    estimated_input_tokens: int = 0
    fallback_code: str | None = None
    focus: GeoReadFocus = "OVERVIEW"


